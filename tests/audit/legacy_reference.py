"""Frozen predicate-only reference relations, used only as an acceptance oracle.

Previously the branch / tile conditions below lived entirely inside prover-side `LookupSpec`
predicates.  These verbatim copies let the audit check that lifting them into relation-4 gates changed
neither direction of acceptance: a row is accepted by the lifted program (auxiliary cells generated by the
hints) exactly when the old predicates accepted it.
"""
from fractions import Fraction

from prover.fpn_prover.circuit.blocks import _dot, _wires, _lookup
from prover.fpn_prover.circuit.microprogram import (
    OP_DENSE_GQA, OP_GDN_LREC, OP_MLA_ABSORBED, OP_MOE_ROUTER_EXPERT, OP_SWA_SINK,
    _exp_cell, _nearest, _softmax, swa_indices,
)
from prover.fpn_prover.ir.gadget_ir import MicroprogramSlot, attaining_rmx, topk_tau


def legacy_microprogram(program, name, *, tokens, experts, top_k, window, sink, conv_width, tau=0,
                        scale=256, extent=None):
    extent = tokens if extent is None else extent

    def dense(normalize, query, *row):
        if normalize not in (0, 1):
            return False
        keys, values = row[:tokens], row[tokens:2*tokens]
        if normalize:
            def normalize_scalar(x):
                return scale if x > 0 else -scale if x < 0 else 0
            query = normalize_scalar(query)
            keys = tuple(map(normalize_scalar, keys))
        scores = tuple(_nearest(Fraction(query*k, scale)) for k in keys[:extent])
        return row[-1] == _softmax(scores, values[:extent], scale)

    def swa(position, query, *row):
        if not 0 <= position < extent:
            return False
        active = swa_indices(position, window, sink)
        scores = tuple(_nearest(Fraction(query*row[i], scale)) for i in active)
        return row[-1] == _softmax(scores, tuple(row[tokens+i] for i in active), scale)

    def moe(*row):
        scores, active, argmax, weights, outputs = (
            row[i*experts:(i+1)*experts] for i in range(5)
        )
        indices = row[5*experts:5*experts+top_k]
        maximum, denominator, result = row[-3:]
        if (not topk_tau(scores, active, indices, tau)
                or not attaining_rmx(scores, active, argmax, maximum, weights, denominator)):
            return False
        return (all(not enabled or weight == _exp_cell(score-maximum, scale)
                    for score, enabled, weight in zip(scores, active, weights, strict=True))
                and result == _nearest(Fraction(_dot(weights, outputs), denominator)))

    def mla(query, rope_query, absorbed_value, *row):
        latent, rope_keys = row[:tokens], row[tokens:2*tokens]
        scores = tuple(_nearest(Fraction(query*k+rope_query*r, scale))
                       for k, r in zip(latent[:extent], rope_keys[:extent], strict=True))
        result = _softmax(scores, latent[:extent], scale)
        return result is not None and row[-1] == _nearest(Fraction(result*absorbed_value, scale))

    def gdn(position, in_range, previous, decay, beta, key, value, *row):
        if not 0 <= position < tokens or in_range != int(position < extent):
            return False
        kernel, history = row[:conv_width], row[conv_width:2*conv_width]
        convolution, state = row[-2:]
        if not in_range:
            return convolution == 0 and state == previous
        if not (0 <= decay <= scale and 0 <= beta <= scale
                and all(x == 0 for x in history[position+1:])):
            return False
        if convolution != _nearest(Fraction(_dot(kernel, history), scale)):
            return False
        decayed = Fraction(decay*previous, scale)
        correction = Fraction(beta*key, scale**2) * (value+convolution - key*decayed/scale)
        return state == _nearest(decayed+correction)

    branches = (
        (OP_DENSE_GQA, 2*tokens+3, dense),
        (OP_SWA_SINK, 2*tokens+3, swa),
        (OP_MOE_ROUTER_EXPERT, 5*experts+top_k+3, moe),
        (OP_MLA_ABSORBED, 2*tokens+4, mla),
        (OP_GDN_LREC, 2*conv_width+9, gdn),
    )
    return MicroprogramSlot.install(program, name, branches, bits=32)


def legacy_gemm_tile_row_block(program, prefix, inner, rows, contract, *, unit=1, bits=24, operand_bits=62):
    """The pre-lift tile (operand / products / box predicates); only the operand width is a parameter."""
    x = _wires(program, prefix, "input", inner, bits)
    rx = _wires(program, prefix, "input_radius", inner, bits)
    z = _wires(program, prefix, "radius_operand", inner, operand_bits)
    gamma = contract.dot_relative_bound(inner)
    for i, (value, radius, scaled) in enumerate(zip(x, rx, z, strict=True)):
        _lookup(program, f"{prefix}.operand.{i}", (value, radius, scaled),
                lambda a, r, b: r >= 0 and b == (
                    gamma.numerator*abs(a) + (gamma.denominator+gamma.numerator)*r))
    eta = Fraction(2)**contract.eta_log2 / Fraction(unit)
    result = x + rx + z
    for i in range(rows):
        w = _wires(program, prefix, f"weight.{i}", inner, bits)
        wr = _wires(program, prefix, f"radius_weight.{i}", inner, bits)
        center, = _wires(program, prefix, f"center.{i}", 1, 61)
        radius, = _wires(program, prefix, f"radius_numerator.{i}", 1, 62)
        observed, = _wires(program, prefix, f"observed.{i}", 1, 61)
        box_delta, = _wires(program, prefix, f"delta.{i}", 1, 61)
        _lookup(program, f"{prefix}.products.{i}", x + z + w + wr + (center, radius),
                lambda *a: (
                    all(b >= abs(c) for b, c in zip(a[3*inner:4*inner],
                                                    a[2*inner:3*inner], strict=True))
                    and a[-1] == _dot(a[inner:2*inner], a[3*inner:4*inner])))
        dot = center
        for a, b in zip(x, w, strict=True):
            dot = dot - a*b
        program.equal(f"{prefix}.center_dot.{i}", dot)
        program.equal(f"{prefix}.difference.{i}", observed-center, box_delta)
        _lookup(program, f"{prefix}.box.{i}", (box_delta, radius),
                lambda d, a: abs(d) <= Fraction(a, gamma.denominator) + eta)
        result += w + wr + (center, radius, observed, box_delta)
    return tuple(wire.args[0] for wire in result)
