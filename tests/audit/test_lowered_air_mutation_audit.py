    # ------------------------------------------------------------------ 2. propagated wire perturbation
    def propagated(self, fx):
        """wire -> set of owners of an AIR-accepted +-1 perturbation ("" = also accepted by the program)."""
        predicates = {lk.name for lk in fx.program.lookups}
        accepted, trials = {}, 0
        for witness in fx.witnesses:
            for wire, spec in fx.program.columns.items():
                low, high = spec.bounds
                for delta in (1, -1):
                    value = witness[wire] + delta
                    if not low <= value <= high:
                        continue
                    modes = ("stale", "full") if wire not in fx.program.hints else ("stale",)
                    for mode in modes:
                        cand = fx.iso.build(witness, {wire: value}, mode)
                        trials += 1
                        if A.table_failures(fx.circuit.table, fx.vector(cand)) != ([], []):
                            continue
                        # Accepted by the table: no algebraic gate sees it.
                        self.assertEqual(fx.iso.violated(cand), set())
                        failures = fx.program.failures(cand)
                        self.assertLessEqual(set(failures), predicates, (wire, failures))
                        accepted.setdefault(wire, set()).update(failures or [""])
        return accepted, trials

    def test_propagated_wire_perturbation_is_rejected_or_owned_by_a_named_predicate(self):
        for name, fx in self.fixtures.items():
            with self.subTest(circuit=name):
                accepted, trials = self.propagated(fx)
                wires = len(fx.program.columns)
                got = {"wires": wires, "trials": trials, "air_pinned": wires - len(accepted),
                       "predicate_or_free": {w: sorted(o) for w, o in sorted(accepted.items())}}
                self.assertEqual(got, EXPECTED[name]["propagated"])
                # A cell the program also accepts is either a declared tie or an input no relation reads
                # in that branch; never an auxiliary cell of a lifted gate (those are pinned by gates).
                for wire, owners in accepted.items():
                    if "" in owners and wire in fx.program.hints:
                        self.assertEqual(fx.program.columns[wire].freedom_kind, Freedom.PERMITTED_TIE)

    # ------------------------------------------------------------------ 3. row deletion
    def test_every_row_deletion_admits_a_forged_witness(self):
        for name, fx in self.fixtures.items():
            with self.subTest(circuit=name):
                c, table, iso = fx.circuit, fx.circuit.table, fx.iso
                classes = fx.classes()
                counts = {"rows": len(c.rows), "individual": 0, "group": 0, "implied": 0}
                covered = set()
                honest = LW.air_values(c, fx.witnesses[0])
                for gate in c.gates:
                    rows = fx.rows[gate.name]
                    if gate.origin != "constraint":
                        kind, values = "individual", iso.limb_mutant(gate, honest)
                    else:
                        kind, witness = classes[gate.name]
                        values = None if witness is None else LW.air_values(c, witness)
                    if kind == "implied":
                        counts["implied"] += len(rows)
                        covered.update(rows)
                        continue
                    allowed = set(rows) if kind == "individual" else {
                        r for g in iso.group(gate) for r in fx.rows[g]}
                    for r in rows:
                        forged = A.row_deletion_vector(c, values, rows, r)
                        V = A.vector(c, forged, SeededRng(r))
                        bad, cells = A.table_failures(table, V)
                        self.assertEqual(cells, [], (gate.name, r))
                        if kind == "individual":
                            # The committed table rejects at exactly row r; the table without row r accepts.
                            self.assertEqual(bad, [r], gate.name)
                            self.assertEqual(A.table_failures(A.delete_row(table, r), V), ([], []))
                        else:
                            self.assertIn(r, bad, gate.name)
                            self.assertLessEqual(set(bad), allowed, gate.name)
                            mutated = table
                            for row in sorted(allowed):
                                mutated = A.delete_row(mutated, row)
                            self.assertEqual(A.table_failures(mutated, V), ([], []))
                        counts[kind] += 1
                        covered.add(r)
                self.assertEqual(covered, set(range(len(c.rows))))
                self.assertEqual(counts, EXPECTED[name]["deletion"])
                self.assertEqual(sorted(n for n, (k, _) in classes.items() if k == "group"),
                                 EXPECTED[name]["group_only"])
                self.assertEqual(sorted(n for n, (k, _) in classes.items() if k == "implied"),
                                 EXPECTED[name]["implied"])

    def test_implied_selector_rows_follow_from_the_lifted_gates(self):
        """The rows no forged vector can violate alone: selector booleanity over the 2-bit range [-2, 1].

        MoE: `index_row.r` makes the selector a sum of boolean one-hot cells (so >= 0).  GDN / SWA:
        `position_low` / `position_high` need s p >= 0 and s (n - 1 - p) >= 0 with n = tokens / extent,
        which has no solution for s < 0 once n >= 2 (SWA in DEMO has extent 1, so its row stays necessary).
        """
        def solvable(s, n):
            return any(s * p >= 0 and s * (n - 1 - p) >= 0 for p in range(-200, 200))

        self.assertFalse(any(solvable(s, n) for s in (-2, -1) for n in (2, 3)))
        self.assertTrue(solvable(-1, 1))
        self.assertEqual(EXPECTED["DEMO"]["implied"], [S + "gdn_lrec.boolean", S + "moe_router_expert.boolean"])
        self.assertEqual(EXPECTED["SLOT3"]["implied"],
                         [S + "gdn_lrec.boolean", S + "moe_router_expert.boolean", S + "swa_sink.boolean"])
        # Every natural forgery of such a selector is rejected by the lifted gates as well.
        for fx, selectors in ((self.fixtures["DEMO"], (2, 4)), (self.fixtures["SLOT3"], (1, 2, 4))):
            names = [n for n in fx.program.columns if n.count(".") == 1 and n.startswith(S + "") and
                     "lane" not in n]
            lanes = {n: 0 for n in fx.program.columns if ".lane" in n and n not in fx.program.hints}
            for index in selectors:
                others = [n for i, n in enumerate(names) if i != index and i in (0, 3)][:2]
                if len(others) < 2:
                    continue
                cand = fx.iso.build(fx.witnesses[0], {**lanes, **dict.fromkeys(names, 0), names[index]: -1,
                                                      others[0]: 1, others[1]: 1}, "full")
                bad = fx.iso.violated(cand)
                self.assertIn(names[index] + ".boolean", bad)
                self.assertGreater(len(bad), 1)

    def test_index_gates_imply_a_boolean_bitmap_with_exactly_top_k_ones(self):
        """Bitmap booleanity and the top-k cardinality have no gate of their own: they follow from the
        index gates for ADVERSARIAL auxiliary cells too.  Exhaustive over small integer cells with the MoE
        branch selected: every assignment satisfying the one-hot booleanity, row, column, value and order
        gates (and the gated-product definition on_i = active_i) has active in {0, 1} summing to top_k."""
        from itertools import product
        for experts, top_k in ((2, 2), (3, 2), (2, 1)):
            cells = (0, 1)                                   # index_onehot_boolean
            solutions = set()
            for flat in product(cells, repeat=experts * top_k):
                rows = [flat[r * experts:(r + 1) * experts] for r in range(top_k)]
                if any(sum(row) != 1 for row in rows):                       # index_row (selector = 1)
                    continue
                index = [sum(i * h for i, h in enumerate(row)) for row in rows]          # index_value
                if any(index[r] - index[r - 1] - 1 < 0 for r in range(1, top_k)):        # index_order
                    continue
                solutions.add(tuple(sum(row[i] for row in rows) for i in range(experts)))   # index_column
            self.assertTrue(solutions)
            for active in solutions:
                self.assertLessEqual(set(active), {0, 1})
                self.assertEqual(sum(active), top_k)
        # The same on the lowered DEMO table: any non-boolean or wrong-cardinality bitmap is rejected with
        # the forger free to choose every auxiliary cell of the index subsystem.
        fx = self.fixtures["DEMO"]
        base = fx.witnesses[2]
        lane = [n for n in fx.program.columns if ".lane" in n and n not in fx.program.hints]
        hot = [MOE + f"index_onehot.{r}.{i}" for r in range(2) for i in range(2)]
        gated = [MOE + "active_gate.0", MOE + "active_gate.1"]
        order = MOE + "index_order.1.slack"
        half = 1 << 6
        tried = 0
        for active in product((-1, 0, 1, 2), repeat=2):
            if active == (1, 1):
                continue
            for cells in product((-1, 0, 1, 2), repeat=4):
                for index in product((-1, 0, 1, 2), repeat=2):
                    gap = index[1] - index[0] - 1
                    if not 0 <= gap < 2 * half:
                        continue                              # no in-range slack cell exists
                    cand = {**base, lane[2]: active[0], lane[3]: active[1], lane[10]: index[0],
                            lane[11]: index[1], **dict(zip(hot, cells)), **dict(zip(gated, active)),
                            order: gap - half}
                    tried += 1
                    self.assertTrue(fx.iso.violated(cand) & {
                        g for g in fx.classes() if ".index_" in g}, (active, cells, index))
        self.assertEqual(tried, EXPECTED["DEMO"]["index_forgeries"])

