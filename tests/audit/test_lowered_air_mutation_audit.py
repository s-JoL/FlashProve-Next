    def test_representative_forgeries_are_rejected_by_python_and_rust(self):
        rust = rust_verifier()
        if not rust and not os.environ.get("FPN_ALLOW_NO_RUST"):
            raise RuntimeError("Rust fpn-verify missing or stale and cargo unavailable "
                               "(set FPN_ALLOW_NO_RUST=1 only for explicit Python-only runs)")
        fx = self.fixtures["DEMO"]
        c, table = fx.circuit, fx.circuit.table
        checked = []

        def both(data, code, root=c.root):
            self.assertEqual(py_verify(data, False, None, root), code)
            if rust:
                self.assertEqual(rust_verify(data, root), "VERIFIED" if code == "VERIFIED" else f"REJECTED: {code}")

        def prove(V, seed, table_=table, hooks=None):
            return FA.prove(table_, V, n_s=LW.air_binding_nonce(c), profile=FOLDED_AIR_V1,
                            rng=SeededRng(seed), hooks=hooks)

        moe = fx.witnesses[2]
        both(prove(fx.vector(moe, 11), 100), "VERIFIED")
        # (a) raw variable perturbation: an accumulator, a slack limb, a gated-product cell.
        index = {n: k for k, n in enumerate(c.variables)}
        acc = next(n for n in c.variables if n.startswith(MOE + "maximum_bound.0#acc"))
        for variable in (acc, LW.limb_name(MOE + "weight_positive.1.slack", 0), MOE + "argmax_gate.0"):
            V = fx.vector(moe, 12)
            k = index[variable]
            V[k] = (V[k] + (-1 if table.flag[k] and V[k] == FA.TABLE - 1 else 1)) % P      # stays in [0, 128)
            rows, cells = A.table_failures(table, V)
            self.assertTrue(rows)
            self.assertEqual(cells, [])
            both(prove(V, 101 + len(checked)), "E_ZEROCHECK")
            checked.append(("raw", variable))
        # (b) forged opened cells, in range, auxiliary cells regenerated by the honest generator: each is
        #     a condition that was previously prover-side only.
        lane = [n for n in fx.program.columns if ".lane" in n and n not in fx.program.hints]
        gemm, gdn = fx.witnesses[0], fx.witnesses[4]
        for label, base, changes, gate in (
                ("gemm wr < |w|", gemm, {"gemm.radius_weight.0.0": 2, "gemm.radius_numerator.0.0":
                                         2 * gemm["gemm.radius_operand.0"]}, "gemm.weight_radius_upper.0.0"),
                ("gemm r_x < 0", gemm, {"gemm.input_radius.0": -1}, "gemm.input_radius_nonneg.0"),
                ("moe dropped expert", moe, {lane[2]: 0, lane[10]: 1}, MOE + "index_column.1"),
                ("moe maximum not attained", moe, {lane[12]: 1}, MOE + "argmax_attains.0"),
                ("gdn decay above scale", gdn, {lane[3]: 257}, GDN + "decay_high"),
                ("dense normalize = 2", gemm, {lane[0]: 2}, S + "dense_gqa.normalize_boolean")):
            cand = fx.iso.build(base, changes, "full")
            self.assertTrue(fx.iso.in_range(cand), label)
            self.assertIn(gate, fx.iso.violated(cand), label)
            V = fx.vector(cand, 13)
            self.assertEqual(A.table_failures(table, V)[1], [], label)
            both(prove(V, 110 + len(checked)), "E_ZEROCHECK")
            checked.append(("lifted", label))
        # (c) an inequality is enforced by the RANGE lookup: slack cell of wr - w >= 0 set to the value the
        #     gate needs for wr - w = -1, its limbs recomposing over F_p with one limb outside [0, 128).
        slack = "gemm.weight_radius_upper.0.0.slack"
        plan = next(pl for pl in c.limb_plans if pl.wire == slack)
        forged = {slack: (-1 - plan.offset) % P,
                  **{name: 127 if i < plan.limbs - 1 else P - 1 for i, name in enumerate(plan.names())}}
        values = LW.air_values(c, fx.iso.build(gemm, {"gemm.radius_weight.0.0": 2, "gemm.radius_numerator.0.0":
                                                      2 * gemm["gemm.radius_operand.0"]}, "full"),
                               overrides=forged)
        V = A.vector(c, values, SeededRng(14))
        rows, cells = A.table_failures(table, V)
        self.assertEqual(rows, [])
        self.assertEqual(cells, [index[plan.names()[-1]]])

        def counts_in_table(layout, table_, vec, rng):
            clipped = [v if not f or v < FA.TABLE else 0 for v, f in zip(vec, table_.flag)]
            m = FA.range_multiplicities(table_, clipped) + [0] * (layout.K - FA.TABLE)
            return FA.build_witness(layout, table_, vec, rng, m=m)

        both(prove(V, 120, hooks={"witness": counts_in_table}), "E_GKR_ROOT")
        checked.append(("range", slack))
        # (d) row deletion: the vector the row-deleted circuit accepts is rejected under the committed
        #     root and VERIFIED under the mutated circuit's own root (the row is what rejects it).
        classes = fx.classes()
        for gate_name, pick in ((MOE + "maximum_bound.0", 0), ("gemm.radius_dot.0", -1),
                                (GDN + "out_range_state", 1)):
            kind, witness = classes[gate_name]
            self.assertEqual(kind, "individual")
            rows = fx.rows[gate_name]
            r = rows[pick]
            V = A.vector(c, A.row_deletion_vector(c, LW.air_values(c, witness), rows, r), SeededRng(15))
