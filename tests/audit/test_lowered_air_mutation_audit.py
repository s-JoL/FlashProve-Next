class Fixture:
    """A lowered circuit, honest witnesses, hand-built gate-isolating recipes and its classification."""

    def __init__(self, name, program, bases, recipes=()):
        self.name, self.program = name, program
        self.circuit = LW.compile_air(program)
        self.used = A.table_integrity(self.circuit)
        self.witnesses = []
        for base in bases:
            assert not program.failures(base), (name, program.failures(base))
            self.witnesses.append(program.complete(base))
        self.iso = A.Isolator(self.circuit, self.witnesses)
        self.recipes = [self.iso.build(self.witnesses[i], changes, mode) for i, changes, mode in recipes]
        self.rows = A.gate_rows(self.circuit)
        self._classes = None

    def vector(self, witness, seed=0):
        """Variable vector of a (complete) wire witness: limbs and accumulators derived, masks random."""
        return A.vector(self.circuit, LW.air_values(self.circuit, witness), SeededRng(seed))

    def classes(self):
        """constraint gate -> ("individual" | "group" | "implied", witness)."""
        if self._classes is None:
            out, iso = {}, self.iso
            for gate in iso.constraint:
                found = next((r for r in self.recipes if iso.isolates(gate, r)), None) or iso.search(gate)
                if found is not None:
                    out[gate.name] = ("individual", found)
                    continue
                names = iso.group(gate)
                found = (next((r for r in self.recipes if iso.within(names, gate, r)), None)
                         or iso.search_group(gate, names))
                out[gate.name] = ("group", found) if found is not None else ("implied", None)
            self._classes = out
        return self._classes


