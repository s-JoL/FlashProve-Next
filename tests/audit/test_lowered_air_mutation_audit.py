class TestLoweredAirMutationAudit(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fixtures = {f.name: f for f in (demo_fixture(), slot3_fixture(), gemm2_fixture())}

    # ------------------------------------------------------------------ shape and honest acceptance
    def test_shape_budget_and_honest_witnesses(self):
        for name, fx in self.fixtures.items():
            with self.subTest(circuit=name):
                c = fx.circuit
                self.assertEqual(c.profile["name"], "fpn2-folded-air-v1")
                self.assertEqual(c.layout.K, 512)
                summary = c.summary()
                self.assertEqual({k: summary[k] for k in ("rows", "variables", "range_checked", "ir_gates")},
                                 EXPECTED[name]["shape"])
                self.assertLessEqual(len(c.rows) + FA.ZK_ROWS, c.layout.K)
                self.assertEqual(len(fx.witnesses), EXPECTED[name]["witnesses"])
                for i, witness in enumerate(fx.witnesses):
                    for seed in (1, 2):          # the mask variables (pad, #zk, unused) are free
                        self.assertEqual(A.table_failures(c.table, fx.vector(witness, seed)), ([], []), i)

    def test_documented_manifest_is_exactly_what_the_blocks_emit(self):
        """`lower.AIR_GATE_FAMILIES` / `AIR_PREDICATE_RESIDUE` name every emitted gate family and every
        remaining predicate, and nothing that no block emits."""
        from prover.fpn_prover.circuit.blocks import gqa_group_attn_block, rmsnorm_block, swiglu_block
        programs = [fx.program for fx in self.fixtures.values()]
        for contract_name in ("mxfp4_e2m1", "fp8_e4m3_block128"):       # 62-bit operand: residual predicates
            program = Program()
            gemm_tile_row_block(program, "gemm", 1, 1, get_contract(contract_name))
            programs.append(program)
        extra = Program()
        rmsnorm_block(extra, "norm", 1)
        swiglu_block(extra, "gate", 1, get_contract("bf16_fp32acc"))
        gqa_group_attn_block(extra, "att", 1, 1, 1, 1, unit=1)
        programs.append(extra)
        wide = Program()                 # a profile whose widest branch is not MoE (single expert)
        slot = install_microprogram(wide, "slot", tokens=8, experts=1, top_k=1, window=2, sink=1, conv_width=1)
        wide.check_bounds()
        row = dict(zip(slot.selectors, (0, 0, 1, 0, 0)))
        row.update(zip(slot.lanes, (5, 1, 1, 256, 7, 0, 5, 256, 7) + (0,) * (len(slot.lanes) - 9)))
        self.assertEqual(wide.failures(row), [])
        self.assertIn("slot.moe_router_expert.index_value.0", wide.failures({**row, slot.lanes[5]: 1}))
        programs.append(wide)
        gates = {LW.relation_family(c.name) for p in programs for c in p.constraints}
        predicates = {LW.relation_family(k.name) for p in programs for k in p.lookups}
        self.assertEqual(gates, set(LW.AIR_GATE_FAMILIES))
